// Firma del APK de entrega. Los datos están en firma/keystore.properties, que no se sube a git.
val firma = Properties().apply {
    val archivo = rootProject.file("firma/keystore.properties")
    if (archivo.exists()) archivo.inputStream().use { load(it) }
}

android {
    namespace = "com.example.huella"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.example.huella"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("entrega") {
            if (!firma.isEmpty) {
                storeFile = rootProject.file(firma.getProperty("storeFile"))
                storePassword = firma.getProperty("storePassword")
                keyAlias = firma.getProperty("keyAlias")
                keyPassword = firma.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            optimization {
                enable = false
            }
            if (!firma.isEmpty) signingConfig = signingConfigs.getByName("entrega")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
}

